import ExcelJS from 'exceljs'
import { describe, it, expect } from 'vitest'
import { UnsupportedDocumentTypeError, detectDocumentType, parseDocument } from './parsers.js'

describe('detectDocumentType', () => {
  it('maps known extensions to their document type', () => {
    expect(detectDocumentType('a.pdf')).toBe('pdf')
    expect(detectDocumentType('a.DOCX')).toBe('docx')
    expect(detectDocumentType('a.xlsx')).toBe('xlsx')
    expect(detectDocumentType('a.csv')).toBe('csv')
    expect(detectDocumentType('a.txt')).toBe('txt')
    expect(detectDocumentType('a.md')).toBe('md')
    expect(detectDocumentType('a.json')).toBe('json')
  })

  it('throws a real, non-fabricated error for an unsupported extension', () => {
    expect(() => detectDocumentType('a.exe')).toThrow(UnsupportedDocumentTypeError)
  })
})

describe('parseDocument', () => {
  it('reads plain text as-is', async () => {
    const result = await parseDocument(Buffer.from('Step 1: open the app.'), 'spec.txt')
    expect(result.documentType).toBe('txt')
    expect(result.text).toBe('Step 1: open the app.')
    expect(result.truncated).toBe(false)
  })

  it('reads markdown as-is', async () => {
    const result = await parseDocument(Buffer.from('# Requirements\n\n- Log in'), 'spec.md')
    expect(result.text).toContain('# Requirements')
  })

  it('validates and normalizes JSON', async () => {
    const result = await parseDocument(Buffer.from('{"title":"Login","steps":["tap"]}'), 'spec.json')
    expect(JSON.parse(result.text)).toEqual({ title: 'Login', steps: ['tap'] })
  })

  it('surfaces a real parse error for invalid JSON rather than silently accepting it', async () => {
    await expect(parseDocument(Buffer.from('{not valid json'), 'spec.json')).rejects.toThrow()
  })

  it('parses CSV rows into a readable table', async () => {
    const result = await parseDocument(Buffer.from('Step,Action\n1,Open app\n2,Tap login'), 'spec.csv')
    expect(result.text).toContain('Step | Action')
    expect(result.text).toContain('1 | Open app')
  })

  it('parses a real xlsx workbook generated by ExcelJS', async () => {
    const workbook = new ExcelJS.Workbook()
    const sheet = workbook.addWorksheet('Cases')
    sheet.addRow(['Step', 'Action'])
    sheet.addRow(['1', 'Open app'])
    const buffer = Buffer.from(await workbook.xlsx.writeBuffer())

    const result = await parseDocument(buffer, 'spec.xlsx')
    expect(result.text).toContain('## Sheet: Cases')
    expect(result.text).toContain('Step | Action')
    expect(result.text).toContain('1 | Open app')
  })

  it('surfaces a real error for a corrupt PDF rather than fabricating extracted text', async () => {
    await expect(parseDocument(Buffer.from('not a real pdf'), 'spec.pdf')).rejects.toThrow()
  })

  it('rejects an unsupported file type before attempting to parse', async () => {
    await expect(parseDocument(Buffer.from('anything'), 'spec.exe')).rejects.toThrow(UnsupportedDocumentTypeError)
  })

  it('marks text as truncated once it exceeds the cap', async () => {
    const huge = 'x'.repeat(60_001)
    const result = await parseDocument(Buffer.from(huge), 'spec.txt')
    expect(result.truncated).toBe(true)
    expect(result.fullTextLength).toBe(60_001)
    expect(result.text.length).toBe(60_000)
  })
})
